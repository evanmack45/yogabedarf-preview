import { chromium } from 'playwright';
const [url, pre, w, h] = process.argv.slice(2);
const b = await chromium.launch({ channel: 'chrome' });
const m = +w < 600;
const p = await b.newPage({ viewport: { width: +w, height: +h }, isMobile: m, hasTouch: m, deviceScaleFactor: m ? 2 : 1 });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (x) => x.type() === 'error' && errs.push(x.text()));
await p.goto(url); await p.waitForTimeout(700);
await p.screenshot({ path: `${pre}-start.png` });
await p.check('input[name=h][value="2"]'); await p.check('input[name=n][value="1"]'); await p.check('input[name=b][value="2"]'); await p.waitForTimeout(800);
await p.screenshot({ path: `${pre}-answered.png` });
await p.click('#start'); await p.waitForTimeout(3000);
await p.screenshot({ path: `${pre}-session.png` });
await p.click('#still'); await p.waitForTimeout(300);
await p.screenshot({ path: `${pre}-still.png` });
for (let k = 0; k < 4; k++) await p.click('#skip');
await p.waitForTimeout(500);
await p.screenshot({ path: `${pre}-done.png` });
await p.screenshot({ path: `${pre}-full.png`, fullPage: true });
console.log(p.url(), errs); await b.close();
